/** Plain 2D vector (no graphics dependency). */
export interface Vec2 {
  x: number;
  y: number;
}

/** Plain 3D vector (no graphics dependency). */
export interface Vec3 {
  x: number;
  y: number;
  z: number;
}

/** Plain quaternion (no graphics dependency). */
export interface Quat {
  x: number;
  y: number;
  z: number;
  w: number;
}

/** Plain RGB color (no graphics dependency). */
export interface ColorRGB {
  r: number;
  g: number;
  b: number;
}
