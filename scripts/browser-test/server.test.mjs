import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import vm from 'node:vm';
import { createHarness } from './server.mjs';

test('local harness confines assets and isolates all mutations', async t => {
  const tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'kotor-harness-fixture-'));
  const game = path.join(tmp, 'game'), dist = path.join(tmp, 'dist');
  await fs.mkdir(path.join(game, 'saves', 'original'), { recursive: true });
  await fs.mkdir(path.join(game, 'data')); await fs.mkdir(dist);
  await fs.writeFile(path.join(game, 'chitin.key'), 'fixture-key-not-an-asset');
  await fs.writeFile(path.join(game, 'data', 'archive.bif'), Buffer.from([0, 1, 2, 3, 4, 5]));
  await fs.writeFile(path.join(game, 'saves', 'original', 'state.res'), 'original');
  await fs.writeFile(path.join(tmp, 'outside'), 'private');
  await fs.symlink(path.join(tmp, 'outside'), path.join(game, 'data', 'link.bif'));
  await fs.writeFile(path.join(dist, 'index.html'), '<html><head></head><body>fixture</body></html>');
  const h = await createHarness({ gameRoot: game, distRoot: dist, port: 0 });
  t.after(async () => { await h.close(); await fs.rm(tmp, { recursive: true, force: true }); });
  const call = (op, p = '', options = {}) => fetch(`${h.base}/__test/${op}?path=${encodeURIComponent(p)}`, { ...options, headers: { 'X-Kotor-Test': h.token, ...options.headers } });
  assert.equal((await fetch(`${h.base}/__test/status`)).status, 403);
  assert.equal((await call('meta', 'chitin.key', { headers: { Origin: 'https://evil.invalid' } })).status, 403);
  assert.equal((await call('meta', '../outside')).status, 400);
  assert.equal((await call('meta', '/etc/passwd')).status, 400);
  assert.equal((await call('meta', 'data\\archive.bif')).status, 400);
  assert.equal((await call('file', 'data/link.bif')).status, 403);
  assert.equal((await call('meta', '.git/config')).status, 403);
  assert.equal((await call('file', 'data/archive.bif', { method: 'PUT', body: 'bad' })).status, 403);
  assert.equal((await call('entry', 'saves', { method: 'DELETE' })).status, 403);
  const range = await call('file', 'DATA/ARCHIVE.BIF', { headers: { Range: 'bytes=2-4' } });
  assert.equal(range.status, 206); assert.deepEqual([...new Uint8Array(await range.arrayBuffer())], [2, 3, 4]);
  assert.equal((await call('file', 'data/archive.bif', { headers: { Range: 'bytes=7-9' } })).status, 416);
  assert.equal((await call('file', 'saves/original/state.res', { method: 'PUT', body: 'copy-only' })).status, 200);
  assert.equal(await fs.readFile(path.join(game, 'saves', 'original', 'state.res'), 'utf8'), 'original');
  assert.equal(await (await call('file', 'saves/original/state.res')).text(), 'copy-only');
  await fs.symlink(path.join(tmp, 'outside'), path.join(h.stateRoot, 'saves', 'link'));
  assert.equal((await call('file', 'saves/link', { method: 'PUT', body: 'bad' })).status, 403);
  assert.equal(await fs.readFile(path.join(tmp, 'outside'), 'utf8'), 'private');
  const html = await (await fetch(`${h.base}/index.html`)).text();
  assert.match(html, /__adapter\.js/);

  // Exercise exactly the injected adapter against the server, including lazy BIF reads.
  const window = { addEventListener() {} };
  const context = vm.createContext({ window, fetch: (url, options) => fetch(new URL(url, h.base), options), Blob, Uint8Array, ArrayBuffer, TextDecoder, DOMException, console });
  vm.runInContext(await (await fetch(`${h.base}/__adapter.js`)).text(), context);
  const root = await window.showDirectoryPicker();
  const data = await root.getDirectoryHandle('data');
  const file = await (await data.getFileHandle('archive.bif')).getFile();
  assert.deepEqual([...new Uint8Array(await file.slice(1, 5).slice(1, 3).arrayBuffer())], [2, 3]);
  const before = await window.__kotorBrowserTest.status();
  assert.deepEqual([...new Uint8Array(await file.slice(0, 2).arrayBuffer())], [0, 1]);
  assert.deepEqual([...new Uint8Array(await file.slice(-2).arrayBuffer())], [4, 5]);
  const after = await window.__kotorBrowserTest.status();
  assert.equal(after.counts.requests - before.counts.requests, 1, 'only the status request, no repeated range downloads');
  const saves = await root.getDirectoryHandle('saves');
  const fresh = await saves.getDirectoryHandle('test', { create: true });
  const handle = await fresh.getFileHandle('roundtrip.res', { create: true });
  assert.ok(handle instanceof window.FileSystemFileHandle);
  const output = await handle.createWritable(); await output.write('abc'); await output.seek(1); await output.write('Z'); await output.close();
  assert.equal(await (await handle.getFile()).text(), 'aZc');
  await handle.remove();
  await assert.rejects(handle.getFile(), e => e.name === 'NotFoundError');
  const ip = await root.getDirectoryHandle('gameinprogress', { create: true });
  const staged = await ip.getFileHandle('state.res', { create: true });
  const stagedOut = await staged.createWritable(); await stagedOut.write('test'); await stagedOut.close();
  await root.removeEntry('gameinprogress', { recursive: true });
  assert.deepEqual(await fs.readdir(path.join(h.stateRoot, 'gameinprogress')), []);
  assert.equal(await fs.readFile(path.join(game, 'chitin.key'), 'utf8'), 'fixture-key-not-an-asset');
});
